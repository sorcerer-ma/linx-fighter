/**
 * 规则内 / 规则外的分流：决定一句话该由本地播报回答，还是交给语言模型。
 *
 * 语音链路里玩家既会问游戏（「我的能量还剩多少」），也会问别的事
 * （「今天天气怎么样」「1 加 1 等于几」）。前者必须由规则与播报回答，
 * 不能让模型碰数值；后者本地答不了，透传给语言模型。
 *
 * 词表是唯一入口：
 * - 命中任一「规则内话题」，就按对局处理；
 * - 没有规则内话题、但看起来在提问或让人代劳，才判成「规则外」；
 * - 两者都不命中就留在本地，按没听清处理——宁可让玩家重说，
 *   也不要让模型猜一句话是不是在问游戏。
 */

/**
 * 规则内话题：招式、资源、轮次、房间、胜负。
 *
 * 单字只收「血 / 轮 / 赢 / 输」这类在对局里高频、在闲聊里少见的词；
 * 「打」「出」这种日常高频单字不收，避免「打车多少钱」被判成游戏问题。
 */
const GAME_TOPIC_RULES = [
  '生命值', '血量', '多少血', '血',
  '能量', '真气', '行动点',
  '大招', '普攻', '强攻', '格挡', '闪避', '承受', '蓄力',
  '招式', '出招', '对局', '战况', '局面', '什么情况', '战绩', '状态',
  '还剩', '剩多少', '剩几次', '还有几', '还有多少', '几次',
  '回合', '轮次', '几回合', '第几轮', '轮', '先手', '后手',
  '伤害', '暴击', '胜负', '赢', '输', '比分',
  '房间', '开局', '玩法', '规则', '对手', '伙伴', '战术',
  '怎么玩', '怎么打', '怎么出招', '怎么操作', '怎么赢',
];

/**
 * 提问特征：问号、疑问词，以及「帮我算 / 讲个笑话」这类让人代劳的说法。
 *
 * 只用来判断「是不是在问」；答不答、由谁答，还要看有没有规则内话题。
 */
const ASK_MARKER_RULES = [
  '?', '？', '吗', '呢',
  '为什么', '为啥', '怎么', '什么', '啥', '多少', '几次', '谁', '哪',
  '几点', '几号', '几度', '星期几', '多久', '几回合', '几轮',
  '是不是', '能不能', '可不可以', '会不会', '有没有', '要不要', '该不该',
  '帮我算', '帮我查', '帮我写', '帮我讲', '帮我翻译', '帮我找', '帮我推荐',
  '给我算', '给我查', '给我讲', '给我写', '给我翻译', '给我说个',
  '讲讲', '讲个', '讲一个', '说个', '说段', '来段',
  '背首', '唱首', '翻译', '解释一下', '介绍一下', '科普',
  '算一下', '算算', '计算', '查一下', '查查', '等于',
];

/** 问题只在开头截一段：语音转写偶尔会把整段话塞进来 */
const QUESTION_LIMIT = 200;

/** 去空白与标点、英文转小写：语音转写常带逗号句号，先抹平再判断 */
export function compactText(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/[\s，,。．.!！?？、"“”'‘’：:；;～~…·]/g, '');
}

function includesAny(text: string, rules: string[]): boolean {
  return rules.some((rule) => text.includes(rule));
}

export type AskScope = 'game' | 'outside';

/**
 * 这句话在问什么：不是提问返回 null，是提问再分规则内 / 规则外。
 *
 * 带问号但抹平后没有内容的（只喊了一个「？」）按没听清处理。
 */
export function askScope(raw: string): AskScope | null {
  const text = compactText(raw);
  if (!text) return null;
  const asked = /[?？]/.test(raw) || includesAny(text, ASK_MARKER_RULES);
  if (!asked) return null;
  return includesAny(text, GAME_TOPIC_RULES) ? 'game' : 'outside';
}

/** 交给语言模型的问题：去首尾空白并截到 200 字，长句不整段塞进去 */
export function outsideQuestion(raw: string): string {
  return raw.trim().slice(0, QUESTION_LIMIT);
}
