/** 汉字 → 音节索引；同一个字只归一个音节，表外字（数字、字母、生僻字）没有映射 */
const CHAR_TO_SYLLABLE = new Map<string, string>();
for (const [syllable, chars] of Object.entries(SYLLABLE_CHARS)) {
  for (const char of chars) {
    if (!CHAR_TO_SYLLABLE.has(char)) CHAR_TO_SYLLABLE.set(char, syllable);
  }
}

/**
 * 查一个汉字的无调音节。
 *
 * 表外字返回 undefined：ASR 语料里出现数字、英文或邻域外的音节时，
 * 调用方应当放弃近音比较，宁可认不出也不要用瞎猜的距离。
 */
export function syllableOf(char: string): string | undefined {
  return CHAR_TO_SYLLABLE.get(char);
}
